
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765/paper/test/',{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>document.querySelector('#pageStats')?.textContent.includes('8 题'),{timeout:30000});
 assert.equal(await page.locator('.question').count(),8,'demo must render eight sample questions');
 assert.equal(await page.locator('#print').isDisabled(),false);
 const count=await page.locator('.tml-math').count();
 assert.ok(count>4,'TeMML should render math rather than plain text: '+count);
 await page.locator('#ansToggle').check();
 assert.equal(await page.locator('#answerList .answer').count(),8);
 await page.locator('[data-mode="book"]').click();
 await page.waitForFunction(()=>document.querySelector('#pageStats')?.textContent.startsWith('8 页'));
 assert.equal(await page.locator('.sheet').count(),8,'one question per page');
 await page.locator('[data-size="a3"]').click();
 await page.waitForFunction(()=>document.body.dataset.paperSize==='a3');
 const geometry=await page.locator('.sheet').first().evaluate(el=>({cssWidth:parseFloat(getComputedStyle(el).width),actualWidth:el.getBoundingClientRect().width}));
 assert.ok(geometry.cssWidth>1500,'A3 must use a true 420mm paper width');
 assert.ok(geometry.actualWidth<1440,'A3 should fit in the desktop stage by scaling: '+JSON.stringify(geometry));
 await page.locator('#titleField').fill('数学二版式检验');
 await page.locator('#titleField').press('Tab');
 await page.waitForFunction(()=>document.querySelector('#title')?.textContent==='数学二版式检验');
 const download=page.waitForEvent('download');
 await page.locator('#save').click();
 const dl=await download;
 assert.ok(dl.suggestedFilename().endsWith('.everflow'));
 const stream=await dl.createReadStream();let chunks=[];for await(const c of stream)chunks.push(c);
 const data=JSON.parse(Buffer.concat(chunks).toString());
 assert.equal(data.questions.length,8);
 assert.equal(data.template,'book');
 assert.deepEqual(errors,[],'page Javascript errors');
 await page.setViewportSize({width:390,height:844});
 await page.locator('#mobileSettings').click();
 assert.equal(await page.locator('#settings').isVisible(),true);
 console.log('PASS: sample 8, Temml math, answers, 8-page book, A3, title, export, mobile controls');
 await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1});
