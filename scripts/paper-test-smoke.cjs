
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:900}});
 await page.addInitScript(()=>{window.__PRINT_CALLED__=0;window.print=()=>{window.__PRINT_CALLED__++}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765/paper/test/',{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>document.querySelector('#pageStats')?.textContent.includes('8 题'),{timeout:30000});
 assert.equal(await page.locator('.question').count(),8,'demo must render eight sample questions');
 assert.equal(await page.locator('.everflow-test-cover').count(),1,'The mother A4 cover should be included by default');
 assert.equal(await page.locator('#coverToggle').isChecked(),true);
 assert.equal(await page.locator('#historyButton').isVisible(),true);
 assert.equal(await page.locator('#print').isDisabled(),false);
 const count=await page.locator('.tml-math').count();
 assert.ok(count>4,'TeMML should render math rather than plain text: '+count);
 await page.locator('#ansToggle').check();
 assert.equal(await page.locator('#answerList .answer').count(),8);
 await page.locator('[data-mode="book"]').click();
 await page.waitForFunction(()=>document.querySelector('#pageStats')?.textContent.startsWith('9 页'));
 assert.equal(await page.locator('.sheet').count(),9,'one A4 cover and eight single-question pages');
 await page.locator('[data-mode="exam"]').click();
 await page.locator('[data-size="a3"]').click();
 await page.waitForFunction(()=>document.body.dataset.paperSize==='a3');
 const geometry=await page.locator('.sheet:not(.everflow-test-cover)').first().evaluate(el=>({cssWidth:parseFloat(getComputedStyle(el).width),actualWidth:el.getBoundingClientRect().width}));
 assert.ok(geometry.cssWidth>1500,'A3 must use a true 420mm paper width');
 const coverGeometry=await page.locator('.everflow-test-cover').evaluate(el=>parseFloat(getComputedStyle(el).width));
 assert.ok(coverGeometry<900&&coverGeometry>780,'Cover must stay true A4 even in A3 exam mode');
 assert.ok(geometry.actualWidth<1440,'A3 should fit in the desktop stage by scaling: '+JSON.stringify(geometry));
 await page.locator('#titleField').fill('数学二版式检验');
 await page.locator('#titleField').press('Tab');
 await page.waitForFunction(()=>document.querySelector('#title')?.textContent==='数学二版式检验');
 const download=page.waitForEvent('download');
 await page.locator('#save').click();
 const dl=await download;
 assert.ok(dl.suggestedFilename().endsWith('.everflow'));
 const stream=await dl.createReadStream();let chunks=[];for await(const c of stream)chunks.push(c);
 const data=JSON.parse(Buffer.concat(chunks).toString());
 assert.equal(data.questions.length,8);
 assert.equal(data.template,'exam');
 assert.equal(data.layout,'a3');
 assert.equal(data.testVisualConfig.withCover,true);
 // Same DOM is used by both actions, but only the explicit Print button invokes window.print.
 await page.locator('[data-mode="exam"]').click();
 await page.locator('[data-size="a4"]').click();
 await page.waitForFunction(()=>document.querySelector('#sheets')?.dataset.layoutReady==='true');
 const n=await page.locator('#sheets .sheet').count();
 const pdfPromise=page.waitForEvent('download',{timeout:90000});
 await page.locator('#downloadPdf').click();
 const pdf=await pdfPromise;
 assert.ok(pdf.suggestedFilename().endsWith('.pdf'));
 const st=await pdf.createReadStream();let size=0,header='';
 for await(const x of st){if(!header)header=x.toString().slice(0,5);size+=x.length}
 assert.equal(header,'%PDF-');assert.ok(size>4000,'empty PDF? '+size);
 assert.equal(await page.evaluate(()=>window.__PRINT_CALLED__),0);
 assert.equal(await page.locator('#sheets .sheet').count(),n,'download must not repaginate');
 await page.locator('#print').click();
 assert.equal(await page.evaluate(()=>window.__PRINT_CALLED__),1);
 // The Test keeps its own recoverable history and can hand over the original questions.
 await page.locator('#historyQuickSave').click();
 await page.locator('#historyButton').click();
 assert.ok(await page.locator('.history-item').count()>=1);
 await page.locator('#historyClose').click();
 const previousTitle=await page.locator('#titleField').inputValue();
 await page.reload({waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>document.querySelector('#pageStats')?.textContent.includes('8 题'),{timeout:20000});
 assert.equal(await page.locator('#titleField').inputValue(),previousTitle,'Test last project should persist across reload');
 await page.locator('#editor').click();
 await page.waitForURL(/\/paper\/editor\/?$/,{timeout:15000});
 await page.waitForFunction(()=>document.querySelectorAll('#orderList .order-item').length===8,{timeout:20000});
 const imported=JSON.parse(await page.evaluate(()=>localStorage.getItem('zuotiben-local-paper-v1')));
 assert.equal(imported.questions.length,8);
 assert.equal(imported.layout,'a4');
 assert.equal(imported.testVisualConfig.withCover,true);
 assert.deepEqual(errors,[],'page Javascript errors');
 await page.setViewportSize({width:390,height:844});
 await page.goto('http://127.0.0.1:8765/paper/test/',{waitUntil:'domcontentloaded'});
 await page.locator('#mobileSettings').click();
 assert.equal(await page.locator('#settings').isVisible(),true);
 console.log('PASS: mother A4 cover, 8 questions, book one-per-page, A3 real paper, local history, editor handoff, PDF and mobile');
 await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1});
